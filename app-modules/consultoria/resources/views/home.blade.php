            <summary><i>05</i><span>Vocês cuidam das renovações?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Sim. Acompanhamos as datas e entramos em contato antes do
              vencimento para ajustar quantidades e condições.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>06</i><span>Como começa um projeto de consultoria?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Com uma conversa. Você conta o contexto, a gente faz as
              perguntas certas e propõe o próximo passo, que pode ser um diagnóstico, uma
              proposta ou só uma orientação.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>07</i><span>Vocês só atendem projetos de IA?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Não. IA é uma frente, ao lado de licenças, consultoria em dados e BI, desenvolvimento de software, infraestrutura e talentos de tecnologia. Muitos projetos começam por uma dessas frentes e chegam à IA depois.</p></div>
          </details>
        </div>
