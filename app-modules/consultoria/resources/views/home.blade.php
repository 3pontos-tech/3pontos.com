        <div class="faq__list" data-stagger>
          <details class="qa" data-reveal>
            <summary><i>01</i><span>Os nossos dados são usados para treinar a IA?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Não. Nos serviços que entregamos, o conteúdo da sua empresa fica dentro do seu ambiente Microsoft 365 e não alimenta o treinamento de modelos públicos. Isso está no contrato do fabricante e revisamos com você antes de começar.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>02</i><span>O Copilot respeita as permissões dos arquivos?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Sim. Ele só enxerga o que a pessoa já poderia abrir sozinha. Por isso a primeira etapa do projeto é revisar permissões: onde elas estão abertas demais, a IA deixa isso evidente rápido.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>03</i><span>Como a LGPD entra num projeto de IA?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Entra antes da ferramenta. Definimos a base legal, o que pode ser enviado à IA, o que precisa de rótulo de confidencialidade e quem audita o uso. O jurídico recebe um relatório do que foi configurado.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>04</i><span>Quanto tempo leva uma implementação?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>O ciclo completo leva cerca de 90 dias. O AI Discovery Day acontece na primeira semana, o protótipo fica pronto em até três semanas e o piloto roda em produção entre a quarta e a décima primeira semana. O prazo exato depende do número de fontes e do estado das permissões.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>05</i><span>Qual licença é preciso ter para começar?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Na maioria dos casos, Microsoft 365 com o complemento de Copilot para os usuários envolvidos. A gente dimensiona quantas licenças fazem sentido no piloto e cota junto com o projeto.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>06</i><span>O treinamento está incluído no projeto?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Sim. Toda implementação sai com capacitação da equipe que vai usar e de um responsável interno. Também vendemos treinamento separado, incluindo trilhas de dados e Power BI.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>07</i><span>E se a empresa ainda não tem dados organizados?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>É o caso mais comum. O diagnóstico aponta o que dá para fazer já com documentos e e-mails, e o que depende de organizar fonte antes. Ninguém precisa esperar o dado perfeito para começar.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>08</i><span>O que é um agente de IA?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>É um assistente que entende um pedido em linguagem comum, consulta as fontes autorizadas da empresa e executa uma tarefa, como responder uma dúvida, preencher um cadastro ou abrir um chamado. Ele trabalha dentro de regras definidas por você, e uma pessoa sempre pode assumir.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>09</i><span>Por que começar por Design Thinking?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Porque o agente certo depende do problema certo. Nos primeiros dias ouvimos quem faz o processo, medimos onde o tempo se perde e só então escolhemos a ferramenta. Isso evita construir um agente que ninguém usa.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>10</i><span>Quanto custa?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>O primeiro dia, o AI Discovery Day, é gratuito. Depois dele você recebe uma proposta com escopo, prazo e custo do protótipo e do piloto, e o custo por transação passa a ser acompanhado desde o início.</p></div>
          </details>
          <details class="qa" data-reveal>
            <summary><i>11</i><span>O agente vai substituir a minha equipe?</span><b aria-hidden="true"></b></summary>
            <div class="qa__body"><p>Não. Ele assume a parte repetitiva, como digitação, conferência e busca de informação, e libera as pessoas para o que exige julgamento. Em todo agente há uma pessoa disponível para assumir quando o caso fugir do padrão.</p></div>
          </details>
